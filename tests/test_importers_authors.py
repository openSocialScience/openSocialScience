"""中文文献的作者抽取：两层，可信度不同，标记也不同。

**背景**：中文核心刊在 OpenAlex / Crossref 里基本查不到，所以导入时「DOI 反查」
与「标题反查」两层对它们几乎全废，记录一路落到「存疑」，作者与年份都是空的。
真跑时三篇 demo 合计 **17 处引用**会印成 `[NO AUTHOR]`。

第一版试过「扫首页、取最后一个像名字的行」——实测只中 2/9，还把页眉的「移动版」
当成了作者名。**会误报的抽取器比没有更糟**，那一版没有上。现在这两层都把两头钉死：

· `cited_as`：期刊网页上的「引用本文」块，**块里的题名要跟已抽出的篇名对得上**才采用。
  一页上常有「上一篇」「下一篇」和参考文献表的题录，随便取一条就会把**别人的**作者
  安到这份文献上，而且作者名、年份、刊名全都合法，错得看不出来。
· `authors_by_layout`：夹在篇名与「摘要」之间的那几行。**只推作者、不核篇名**，
  所以用它的记录继续带 `[UNVERIFIED]`。
"""

from __future__ import annotations

import pytest

from oss.core.importers import authors_by_layout, cited_as


# ── 「引用本文」块 ────────────────────────────────────────────────
@pytest.mark.parametrize("block,title,want_authors,want_year", [
    # 写法一：作者. 年. 题名[J]. 刊, 卷(期): 页.
    ("引用本文\n翟学伟. 2014. 信任的本质及其文化[J]. 社会, 34(1): 1-26.\n",
     "信任的本质及其文化", ["翟学伟"], 2014),
    # **写法二：年在题名之后。**只认写法一时，这一篇的作者一直是空的（真跑时就是）
    ("引用本文\n刘力, 阮荣平. 信仰与捐赠:宗教让人更加慷慨了吗?[J]. 南方经济, 2018, 37(11): 103-120.\n",
     "[UNVERIFIED] 信仰与捐赠:宗教让人更加慷慨了吗?", ["刘力", "阮荣平"], 2018),
    ("胡荣, 李静雅. 2006. 城市居民信任的构成及影响因素[J]. 社会, 26(6).\n",
     "城市居民信任的构成及影响因素", ["胡荣", "李静雅"], 2006),
])
def test_引用本文块(block: str, title: str, want_authors: list[str], want_year: int) -> None:
    assert cited_as(block, title) == (want_authors, want_year)


def test_题名对不上就不要_哪怕块本身是好的() -> None:
    """**这是这一层唯一的防线。**一页上「上一篇」「下一篇」的题录格式完全合法，
    取错一条就把别人的作者安到这份文献上，而作者名、年份、刊名都挑不出毛病。
    """
    page = ("«上一篇\n张三. 2019. 完全不相干的另一篇[J]. 某刊, 1(1): 1-9.\n"
            "下一篇»\n李四. 2020. 又一篇别的[J]. 某刊, 2(2): 1-9.\n")
    assert cited_as(page, "信任的本质及其文化") == ([], 0)
    # 同一页上只要有对得上的那一条，就取它
    page += "翟学伟. 2014. 信任的本质及其文化[J]. 社会, 34(1): 1-26.\n"
    assert cited_as(page, "信任的本质及其文化") == (["翟学伟"], 2014)


def test_篇名太短不匹配() -> None:
    """篇名只有三两个字时「一方包含另一方」几乎必中，等于没有防线。"""
    assert cited_as("张三. 2019. 信任[J]. 某刊.\n", "信任") == ([], 0)


# ── 版面位置 ──────────────────────────────────────────────────
def _page(*lines: str) -> str:
    return "\n".join(lines)


def test_一行多个作者按空格切_不是剥掉空格() -> None:
    """**四份真文件都是这么漏掉的。**剥掉空格会把 `吕炜 姬明曦 杨沫` 拼成
    七个字的一坨，过不了姓名那条判据。
    """
    t = _page("人口流动能否影响社会信任", "———基于中国综合社会调查的经验研究",
              "吕炜 姬明曦 杨沫", "内容提要:基于CGSS2013微观调查数据集……")
    assert authors_by_layout(t, "人口流动能否影响社会信任") == ["吕炜", "姬明曦", "杨沫"]


def test_两字名中间的空格要并回去() -> None:
    """两字名的通行印法是中间加空格，为了跟三字名对齐：
    `李　丁　卢云峰` 是两位作者，`刘　　　能` 是一位。
    """
    t = _page("华人社会中的宗教信仰", "与公共参与:以台湾地区为例",
              "李　丁　卢云峰", "内容提要　本文利用台湾社会变迁调查数据……")
    assert authors_by_layout(t, "华人社会中的宗教信仰") == ["李丁", "卢云峰"]
    t2 = _page("中国都市地区普通公众参加社会捐助活动", "的意愿和行为取向分析",
               "刘　　　能", "Abstract :")
    assert authors_by_layout(t2, "中国都市地区普通公众参加社会捐助活动") == ["刘能"]


def test_名被断成两行也要拼回去() -> None:
    """实测「周洁」印成「周」「洁*」两行。"""
    t = _page("行为公共管理学视角下公众的政府满意度:", "概念、测量及影响因素",
              "贾奇凡", "尹泽轩", "周", "洁*", "【摘要】公众的政府满意度是……")
    assert authors_by_layout(t, "行为公共管理学视角下公众的政府满意度:概念、测量及影响因素") == \
        ["贾奇凡", "尹泽轩", "周洁"]


@pytest.mark.parametrize("anchor", ["【摘要】正文……", "摘", "Abstract :", "内容提要:正文……"])
def test_摘要那一行的几种印法都认(anchor: str) -> None:
    """英文刊名页用 `Abstract`；有的 PDF 把「【摘要】」断成「【摘」「要】」两行。"""
    t = _page("城市公共服务满意度影响因素再探究", "———锚定场景法的应用", "孙宗锋*", anchor)
    assert authors_by_layout(t, "城市公共服务满意度影响因素再探究") == ["孙宗锋"]


@pytest.mark.parametrize("junk,why", [
    ("·劳动就业·", "栏目标签。**剥掉间隔号会造出假名字**——「劳动就业」正好四个汉字"),
    ("2004 年第2 期", "页眉的卷期。剥掉数字会造出「年第期」这个假名字"),
    ("北京大学政府管理学院", "单位"),
    ("◆专栏: 跨学科视野", "栏目"),
])
def test_夹在中间但不是作者的都要排掉(junk: str, why: str) -> None:
    t = _page("人口流动能否影响社会信任", junk, "吕炜 姬明曦 杨沫", "内容提要:……")
    assert authors_by_layout(t, "人口流动能否影响社会信任") == ["吕炜", "姬明曦", "杨沫"], why


def test_文件里真没有作者就不要编() -> None:
    """两份真文件是这样：一份只印单位不印姓名，一份题名之后直接是摘要。
    **这时 `[NO AUTHOR]` 占位就是正确行为**，编一个作者比留占位糟得多。
    """
    只有单位 = _page("变迁社会中的社会信任：存量与变化",
                 "(1．北京大学政府管理学院，北京 100871)", "摘")
    assert authors_by_layout(只有单位, "变迁社会中的社会信任：存量与变化") == []
    直接摘要 = _page("青年人获得感现状及其影响因素", "摘　要：本研究采用……")
    assert authors_by_layout(直接摘要, "青年人获得感现状及其影响因素") == []


def test_找不到篇名那一行就不推() -> None:
    """上界没钉住的话，「作者区」会一路往上圈到页眉与栏目。"""
    assert authors_by_layout(_page("张三", "【摘要】……"), "一个不在文件里的篇名") == []
