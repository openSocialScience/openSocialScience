from __future__ import annotations

#: **退化列**：一列里众数占到这个比例就提醒（仿真骨架设计稿 4.3 甲）。
#:
#: 合成样本的方差会被压扁（Bisbee 2024）——一百个小人回答同一道题，分布比真人窄得多；
#: 拿它当调查数据用，标准误会假小、显著性会假强，而**现在没有任何一步会发现**。
#:
#: 0.95 是 2026-09-19 用户拍板的，依据是真实数据量出来的分布：
#: GSS（七万五千份问卷、1972–2024）里取值数 2–10 的量表题 4880 道，众数占比的分布是
#: 中位数 52.7%、75 分位 71.7%、90 分位 89.7%、95 分位 95.6%。按 0.95 划线，
#: **真人题目里 5.6% 会被提醒**（0.90 线是 9.6%、0.80 线是 17.8%）。
#:
#: 取宽的那一档，是因为这条是**警告**：误报多了人会整片忽略它——
#: 「宁漏勿滥」跟因果措辞那条同一个道理。真人问卷里本来就有大量合法的偏态题
#: （「你有没有做过 X」九成五答没有），拿它们反复打扰作者，这条门就没人信了。
DEGENERATE_MODE_SHARE = 0.95

#: **取值数**那条判据**不另设**：整列一个值已经由画像的 `constant_columns` 认出来了，
#: 再写一遍是冗余；而「取值数 ≤ 2」拦不得——GSS 里 28.5% 的题目本来就是二值的。
#: 五档量表只被用了两档这种情形，光看列本身分不出来，要靠跟真实数据对账那一路（4.3 乙）。

#: **方差比**：合成 SD ÷ 真实 SD 落在这个区间外就提醒（4.3 乙）。**两头都报**——
#: 压扁是 Bisbee 的发现，夸大同样说明这批小人不像真人。
#:
#: [0.70, 1.43] 是 2026-09-19 用户拍板的，依据同样是拿真实数据量出来的：
#: GSS 2018 年那批人与 2022 年那批人（**两批不同的真人**）答同一套题，454 道可比的量表题里，
#: 标准差之比中位数 0.99、5 分位 0.88、95 分位 1.09——**真人跟真人之间其实很稳**。
#: 按 [0.70, 1.43] 划线，两批真人里只有 1.5% 会落在区间外（[0.80,1.25] 是 3.1%、
#: [0.50,2.00] 是 0.9%）。取比真人之间宽得多的这一档，是给「不同人群、不同量表」
#: 这类正当差异留余地——这条只在作者自己声明「这批小人代表真人」时才查，
#: 但声明了不等于该被一个过紧的区间反复打扰。
VARIANCE_RATIO_BAND = (0.70, 1.43)

#: 对不上账时处方的级别。**must**：不硬停（补一份真实数据不是一两分钟的事），
#: 但 `oss route` 不许驳回——作者自己声明了这批小人代表真人，对不上账就是这个主张不成立，
#: 要么改方法重跑、要么把主张撤掉（2026-09-19 用户拍板）。
BENCHMARK_LEVEL = "must"
